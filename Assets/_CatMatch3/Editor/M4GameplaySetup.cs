using System;
using System.IO;
using System.Linq;
using CatMatch3.Runtime;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace CatMatch3.Editor
{
    public static class M4GameplaySetup
    {
        private const string Menu = "CatMatch3/Setup/Apply M4 Two-Level Gameplay";
        private const string ScenePath = "Assets/_CatMatch3/Scenes/Gameplay.unity";
        private const string DataPath = "Assets/_CatMatch3/Data";

        [MenuItem(Menu)]
        public static void Apply()
        {
            if (!CanApply()) return;
            try { ApplyOrThrow(); }
            catch (Exception exception)
            {
                Debug.LogError("CatMatch3 M4 setup did not finish. Completed asset/infrastructure steps can be safely rerun. " + exception.Message);
                Debug.LogException(exception);
            }
        }

        internal static void ApplyOrThrow()
        {
            if (!CanApply()) throw new InvalidOperationException("Exit Play Mode and wait for compilation before setup.");
            var previous = SceneManager.GetActiveScene();
            var previousBuild = EditorBuildSettings.scenes;
            Scene scene = default;
            bool openedHere = false;
            bool buildChanged = false;
            int undoGroup = -1;
            try
            {
                scene = SceneManager.GetSceneByPath(ScenePath);
                if (scene.IsValid() && scene.isLoaded && scene.isDirty)
                    throw new InvalidOperationException("Save or revert unsaved Gameplay edits before M4 setup.");
                // Independently completed steps remain usable after a partial attempt.
                var first = EnsureLevel(1);
                var second = EnsureLevel(2);
                ValidatePair(first, second);
                M1BoardSetup.ApplyOrThrow();
                scene = SceneManager.GetSceneByPath(ScenePath);
                if (!scene.IsValid() || !scene.isLoaded)
                {
                    scene = EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Additive);
                    openedHere = true;
                }
                if (!scene.IsValid() || !scene.isLoaded || EditorSceneManager.IsPreviewScene(scene))
                    throw new InvalidOperationException("Gameplay must be a valid, loaded Editor scene.");
                var controllers = scene.GetRootGameObjects().SelectMany(r => r.GetComponentsInChildren<BoardPrototype>(true)).ToArray();
                if (controllers.Length != 1) throw new InvalidOperationException("Gameplay requires exactly one existing BoardPrototype.");
                var controller = controllers[0];
                var serialized = new SerializedObject(controller);
                CheckReference(serialized, "level1", first);
                CheckReference(serialized, "level2", second);

                Undo.IncrementCurrentGroup();
                undoGroup = Undo.GetCurrentGroup();
                Undo.SetCurrentGroupName("Apply CatMatch3 M4 Gameplay");
                Undo.RecordObject(controller, "Wire M4 level assets");
                serialized.FindProperty("level1").objectReferenceValue = first;
                serialized.FindProperty("level2").objectReferenceValue = second;
                bool changed = serialized.ApplyModifiedProperties();
                if (changed)
                {
                    EditorUtility.SetDirty(controller);
                    EditorSceneManager.MarkSceneDirty(scene);
                    if (!EditorSceneManager.SaveScene(scene)) throw new IOException("Unity could not save Gameplay references.");
                }
                // One enabled Gameplay startup entry; retain every unrelated entry in its original order.
                var build = new[] { new EditorBuildSettingsScene(ScenePath, true) }
                    .Concat(EditorBuildSettings.scenes.Where(s => s.path != ScenePath)).ToArray();
                if (!EditorBuildSettings.scenes.Select(s => (s.path, s.enabled)).SequenceEqual(build.Select(s => (s.path, s.enabled))))
                {
                    buildChanged = true;
                    EditorBuildSettings.scenes = build;
                }
                Undo.CollapseUndoOperations(undoGroup);
                undoGroup = -1;
                Debug.Log("CatMatch3 M4 applied. Level assets validated and wired; Gameplay is the first shared build scene. " +
                    "Open Gameplay alone in portrait and enter Play Mode. HUD, tutorial and result buttons are generated by BoardView. " +
                    "Existing level content, camera, input, other build entries and portrait settings were preserved.");
            }
            catch
            {
                if (buildChanged) EditorBuildSettings.scenes = previousBuild;
                if (undoGroup >= 0) Undo.RevertAllDownToGroup(undoGroup);
                throw;
            }
            finally
            {
                try
                {
                    if (openedHere && scene.IsValid() && !EditorSceneManager.CloseScene(scene, true))
                        Debug.LogError("CatMatch3 M4: could not close Gameplay opened by setup.");
                }
                finally
                {
                    if (previous.IsValid() && previous.isLoaded && !EditorSceneManager.IsPreviewScene(previous) &&
                        SceneManager.GetActiveScene() != previous && !SceneManager.SetActiveScene(previous))
                        Debug.LogError("CatMatch3 M4: could not restore the previously active scene.");
                }
            }
        }

        [MenuItem(Menu, true)]
        private static bool CanApply() { return !EditorApplication.isPlayingOrWillChangePlaymode && !EditorApplication.isCompiling; }

        private static LevelDefinition EnsureLevel(int number)
        {
            if (!AssetDatabase.IsValidFolder(DataPath))
                throw new InvalidOperationException("The CatMatch3 Data folder is missing or has not finished importing.");
            string path = DataPath + "/Level" + number + ".asset";
            var existing = AssetDatabase.LoadMainAssetAtPath(path);
            if (existing == null && File.Exists(path))
            {
                AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);
                existing = AssetDatabase.LoadMainAssetAtPath(path);
            }
            if (existing != null)
            {
                if (!(existing is LevelDefinition definition)) throw new InvalidOperationException(path + " contains a different asset type; it was preserved.");
                if (EditorUtility.IsDirty(definition))
                    throw new InvalidOperationException("Save or revert unsaved edits to " + path + " before validating setup.");
                definition.ToConfiguration();
                return definition;
            }
            if (File.Exists(path) || Directory.Exists(path) || File.Exists(path + ".meta"))
                throw new IOException(path + " has conflicting/unimported content or orphaned metadata. Nothing was overwritten.");
            var created = ScriptableObject.CreateInstance<LevelDefinition>();
            try
            {
                created.name = "Level" + number;
                created.InitializeDefaults(number);
                created.ToConfiguration();
                AssetDatabase.CreateAsset(created, path);
                AssetDatabase.SaveAssetIfDirty(created);
                return created;
            }
            catch
            {
                if (!AssetDatabase.Contains(created)) UnityEngine.Object.DestroyImmediate(created);
                throw;
            }
        }

        private static void ValidatePair(LevelDefinition first, LevelDefinition second)
        {
            if (first == second || first.ToConfiguration().Identifier == second.ToConfiguration().Identifier)
                throw new InvalidOperationException("Level 1 and Level 2 require distinct assets and identifiers.");
        }

        private static void CheckReference(SerializedObject controller, string property, LevelDefinition expected)
        {
            var existing = controller.FindProperty(property).objectReferenceValue;
            if (existing != null && existing != expected)
                throw new InvalidOperationException("Existing " + property + " points to another asset. Reference preserved; resolve the conflict before rerunning.");
        }
    }
}
